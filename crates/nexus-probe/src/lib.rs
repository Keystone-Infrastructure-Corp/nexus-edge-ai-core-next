//! `nexus-probe` library — host enumeration + config generation.
//!
//! The companion CLI (`crates/nexus-probe/src/main.rs`) builds a
//! [`Manifest`] (serialized to `device-manifest.json`) and, via
//! `emit-config`, generates a complete capability-based `nexus.toml`
//! from the detected hardware.
//!
//! Wire shape is stable: changing serde field names / order is a
//! breaking change for `device-manifest.json` consumers.

use std::collections::HashSet;
use std::fs;
use std::process::Command;

use chrono::Utc;
use serde::{Deserialize, Serialize};

pub mod generate;
pub mod profile;

pub use generate::{generate_config, render_toml};
pub use profile::{DecodeCapability, ForcedProfile, HardwareProfile, InferenceDevice};

// ---------------------------------------------------------------------------
// Wire types — exposed so external callers (engine + tests) can consume them.
// ---------------------------------------------------------------------------

#[derive(Debug, Serialize, Deserialize, Default)]
pub struct Manifest {
    pub schema: u32,
    pub captured_at: String,
    pub host: HostInfo,
    pub cpu: CpuInfo,
    pub memory: MemoryInfo,
    pub accelerators: Accelerators,
    pub runtimes: Runtimes,
    /// Recommended capability profile (`intel-igpu` / `intel-npu` / `hailo` /
    /// `amd-rocm` / `amd-vulkan` / `nvidia` / `cpu` / `dev`) derived from the
    /// detected CPU + accelerators. See docs/HARDWARE_MATRIX.md for the
    /// mapping. Advisory label retained for cloud observability; the live
    /// nexus.toml is generated by `emit-config`, not selected by this label.
    pub recommended_profile: String,
}

#[derive(Debug, Serialize, Deserialize, Default)]
pub struct HostInfo {
    pub hostname: String,
    pub os: String,
    pub arch: String,
    pub kernel: String,
}

#[derive(Debug, Serialize, Deserialize, Default)]
pub struct CpuInfo {
    pub model_name: String,
    pub physical_cores: usize,
    pub logical_cores: usize,
}

#[derive(Debug, Serialize, Deserialize, Default)]
pub struct MemoryInfo {
    pub total_kib: u64,
}

#[derive(Debug, Serialize, Deserialize, Default)]
pub struct Accelerators {
    pub intel_igpu: bool,
    /// A discrete Intel Arc A-series (DG2) GPU is present. Folded into the
    /// Intel-GPU profile decision alongside `intel_igpu`; the field name is
    /// retained for `device-manifest.json` wire stability.
    pub intel_arc_140v: bool,
    pub intel_npu: bool,
    pub nvidia_gpu: bool,
    /// Total VRAM of NVIDIA GPU 0 in MiB, read from `nvidia-smi`. `None`
    /// when no NVIDIA card is present, or when the proprietary driver is
    /// not yet live (`nvidia-smi` missing or erroring) — which is also the
    /// state on a box awaiting the post-driver-install reboot. Consumers
    /// treat `None` as "unknown" and under-provision rather than guess.
    ///
    /// GPU 0 specifically, because that is the device the CUDA execution
    /// provider binds by default (see `cuda_device_id` in
    /// `nexus-inference`).
    #[serde(default)]
    pub nvidia_vram_mib: Option<u64>,
    pub apple_silicon: bool,
    /// AMD Radeon iGPU (Phoenix-class Ryzen 7000/8000 APUs) or any
    /// AMD dGPU. Used for hardware H.264/HEVC decode via VA-API
    /// (Mesa Gallium). Inference EP for AMD is not wired today —
    /// ROCm on Phoenix gfx1035 is an experimental spike.
    pub amd_igpu: bool,
    /// Hailo-8 / Hailo-8L M.2 accelerator (PCI vendor 0x1e60).
    /// A Hailo present recommends the `hailo` capability profile.
    /// Until `M_HAILO_EP` lands the engine still falls back to the
    /// CPU EP at runtime — the detection is what unlocks the
    /// auto-profile mapping ahead of the EP work.
    pub hailo: bool,
    /// True only when an AMD GPU whose PCI device ID is on the
    /// ROCm-supported allowlist (discrete CDNA / RDNA2 / RDNA3) is
    /// present. Default-deny: Phoenix / Rembrandt iGPUs (gfx1035 /
    /// gfx1103) and any unvetted part stay `false` and route to the
    /// Vulkan EP. Ported from `scripts/lib/install-common.sh`
    /// (`_ROCM_SUPPORTED_PCI_IDS`) so the ROCm-vs-Vulkan EP decision
    /// lives in exactly one place. `#[serde(default)]` keeps older
    /// `device-manifest.json` (which lacks this key) deserializable.
    #[serde(default)]
    pub amd_rocm_capable: bool,
    pub render_nodes: Vec<String>,
    pub accel_nodes: Vec<String>,
}

#[derive(Debug, Serialize, Deserialize, Default)]
pub struct Runtimes {
    pub gstreamer: Option<String>,
    pub onnxruntime: Option<String>,
    pub docker: Option<String>,
}

