fn probe_host() -> HostInfo {
    HostInfo {
        hostname: hostname_or("unknown"),
        os: std::env::consts::OS.into(),
        arch: std::env::consts::ARCH.into(),
        kernel: shell_out("uname", &["-r"]).unwrap_or_default(),
    }
}

fn hostname_or(default: &str) -> String {
    shell_out("hostname", &[]).unwrap_or_else(|| default.into())
}

fn probe_cpu() -> CpuInfo {
    let model = read_first_field("/proc/cpuinfo", "model name").unwrap_or_default();
    let logical = std::thread::available_parallelism()
        .map(|n| n.get())
        .unwrap_or(0);
    // Physical: count unique "physical id"s on Linux; on other OS just use logical.
    let physical = if cfg!(target_os = "linux") {
        count_unique_field("/proc/cpuinfo", "physical id").unwrap_or(logical)
    } else {
        logical
    };
    CpuInfo {
        model_name: model,
        physical_cores: physical,
        logical_cores: logical,
    }
}

fn probe_memory() -> MemoryInfo {
    let total = read_first_field("/proc/meminfo", "MemTotal")
        .and_then(|s| {
            s.split_whitespace()
                .next()
                .and_then(|x| x.parse::<u64>().ok())
        })
        .unwrap_or(0);
    MemoryInfo { total_kib: total }
}

fn probe_accelerators() -> Accelerators {
    let lspci = shell_out("lspci", &["-nn"]).unwrap_or_default();
    let det = detect_accel_from_lspci(&lspci);
    let render_nodes = list_dir_starts_with("/dev/dri", "renderD");
    let accel_nodes = list_dir_starts_with("/dev/accel", "");
    Accelerators {
        intel_igpu: det.intel_igpu,
        intel_arc_140v: det.intel_arc_dgpu,
        // A /dev/accel node is a runtime signal an NPU exists even when
        // lspci can't name it; keep it as an additional positive.
        intel_npu: det.intel_npu || !accel_nodes.is_empty(),
        nvidia_gpu: det.nvidia_gpu,
        nvidia_vram_mib: if det.nvidia_gpu {
            probe_nvidia_vram_mib()
        } else {
            None
        },
        apple_silicon: cfg!(all(target_os = "macos", target_arch = "aarch64")),
        amd_igpu: det.amd_igpu,
        hailo: det.hailo,
        // ROCm-vs-Vulkan: read PCI device IDs from sysfs and match the
        // allowlist (default-deny). Linux-only; false elsewhere.
        amd_rocm_capable: detect_amd_rocm_capable(),
        render_nodes,
        accel_nodes,
    }
}

/// Total VRAM of NVIDIA GPU 0, in MiB, via `nvidia-smi`.
///
/// Returns `None` whenever the answer is not trustworthy: no driver, an
/// erroring `nvidia-smi`, or unparseable output. Callers under-provision
/// on `None` rather than guessing.
///
/// The installer runs `install_drivers` before `emit-config`, so by the
/// time the generated `nexus.toml` is written the driver is live and this
/// answers. When the driver install demands a reboot the installer exits
/// before generating a config at all, and the post-reboot re-run probes a
/// working driver.
fn probe_nvidia_vram_mib() -> Option<u64> {
    let out = shell_out(
        "nvidia-smi",
        &[
            "--query-gpu=memory.total",
            "--format=csv,noheader,nounits",
            "--id=0",
        ],
    )?;
    parse_nvidia_smi_vram_mib(&out)
}

/// Parse `nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits`
/// output (a bare MiB integer per GPU) into the first GPU's VRAM.
///
/// Rejects zero, which `nvidia-smi` reports for a GPU in an error state
/// and which would otherwise bucket as an absurdly small card.
fn parse_nvidia_smi_vram_mib(out: &str) -> Option<u64> {
    out.lines()
        .map(str::trim)
        .find(|l| !l.is_empty())
        .and_then(|l| l.parse::<u64>().ok())
        .filter(|mib| *mib > 0)
}

/// Accelerator presence derived from a single pass over `lspci -nn`. The
/// one detector shared by [`build_manifest`] (→ `device-manifest.json` /
/// `emit-config`) and [`accel_tags`] (→ the installer's driver
/// selection), so the generated `nexus.toml` and the drivers actually
/// installed can never disagree about what hardware is present.
#[derive(Debug, Default, Clone, Copy)]
struct AccelDetection {
    intel_igpu: bool,
    intel_arc_dgpu: bool,
    intel_npu: bool,
    nvidia_gpu: bool,
    amd_igpu: bool,
    hailo: bool,
}

/// Parse `lspci -nn` output into [`AccelDetection`]. Device-ID-precise,
/// matching the vocabulary the installer historically detected in bash
/// (`scripts/lib/install-common.sh`), so moving detection here does not
/// regress driver selection. Each rule is applied per line (as `grep`
/// would), then OR-ed across the device list.
fn detect_accel_from_lspci(lspci_nn: &str) -> AccelDetection {
    let mut d = AccelDetection::default();
    for line in lspci_nn.lines() {
        let lower = line.to_ascii_lowercase();
        // Intel iGPU/dGPU: display-class VGA with vendor 8086 (covers
        // UHD, Iris Xe, Arc 140V, and discrete Arc — the latter is also
        // tagged below).
        if line.contains("VGA") && line.contains("[8086:") {
            d.intel_igpu = true;
        }
        // Intel Arc A-series discrete (DG2 silicon): device IDs 56a0..56af.
        if line_has_arc_dgpu(line) {
            d.intel_arc_dgpu = true;
        }
        // Intel NPU: Meteor Lake (7d1d), Arrow Lake (643e), Lunar Lake
        // (7e4e), or the "Processing accelerators" PCI class for a future
        // SKU the device-ID list misses.
        if line.contains("[8086:7d1d]")
            || line.contains("[8086:643e]")
            || line.contains("[8086:7e4e]")
            || (lower.contains("processing accelerator") && lower.contains("[8086:"))
        {
            d.intel_npu = true;
        }
        // NVIDIA discrete (vendor 10de).
        if (line.contains("VGA") || line.contains("3D controller")) && line.contains("[10de:") {
            d.nvidia_gpu = true;
        }
        // AMD iGPU/dGPU (vendor 1002): Radeon 680M/780M iGPUs and any dGPU.
        if (line.contains("VGA")
            || line.contains("3D controller")
            || line.contains("Display controller"))
            && line.contains("[1002:")
        {
            d.amd_igpu = true;
        }
        // Hailo-8 / Hailo-8L M.2 accelerator (vendor 1e60).
        if line.contains("[1e60:") {
            d.hailo = true;
        }
    }
    d
}

/// True when `line` carries an Intel Arc A-series discrete device ID
/// (`[8086:56XY]` with `X` in `a..=f`), i.e. the bash
/// `\[8086:56[a-f][0-9a-f]\]` match. Implemented without a regex
/// dependency.
fn line_has_arc_dgpu(line: &str) -> bool {
    for (idx, _) in line.match_indices("[8086:56") {
        let rest = &line[idx + "[8086:56".len()..];
        let mut chars = rest.chars();
        if let (Some(a), Some(b), Some(']')) = (chars.next(), chars.next(), chars.next()) {
            if matches!(a, 'a'..='f' | 'A'..='F') && b.is_ascii_hexdigit() {
                return true;
            }
        }
    }
    false
}

/// Static allowlist of AMD PCI device IDs (the `XXXX` in `1002:XXXX`) that
/// ROCm OFFICIALLY supports: discrete RDNA2 (gfx1030), RDNA3
/// (gfx1100/1101/1102), and CDNA (gfx908/gfx90a/gfx942). This is the
/// single source of truth for the ROCm-vs-Vulkan decision; the bash
/// installer queries it via `nexus-probe accel-tags` (the duplicate
/// `_ROCM_SUPPORTED_PCI_IDS` array was removed). Deliberately
/// DEFAULT-DENY: anything NOT listed (Phoenix / Rembrandt iGPUs gfx1035
/// / gfx1103, unvetted or brand-new parts) routes to the Vulkan(WebGPU)
/// EP, never ROCm.
const ROCM_SUPPORTED_PCI_IDS: &[&str] = &[
    // CDNA — MI100 (gfx908)
    "738c", "738e", //
    // CDNA2 — MI200 / MI210 / MI250 (gfx90a)
    "7408", "740c", "740f", "7410", //
    // CDNA3 — MI300 (gfx942)
    "74a0", "74a1", "74a5", "74a9", "74b5", "74b9", "74bd", //
    // RDNA2 — Navi 21, RX 6800/6900 (gfx1030)
    "73a1", "73a2", "73a3", "73a5", "73ab", "73af", "73bf", //
    // RDNA3 — Navi 31 RX 7900 (gfx1100), Navi 32 RX 7700/7800 (gfx1101),
    // Navi 33 RX 7600 (gfx1102)
    "744c", "745e", "747e", "7480", "7483",
];

/// Pure allowlist check: true when `device_id` — the `device` portion of
/// `1002:device` (with or without a `0x` prefix, any case) — is a
/// ROCm-supported part. The pure half of the ROCm-vs-Vulkan classifier so
/// it can be unit-tested without sysfs.
fn amd_rocm_supported(device_id: &str) -> bool {
    let id = device_id
        .trim()
        .trim_start_matches("0x")
        .to_ascii_lowercase();
    ROCM_SUPPORTED_PCI_IDS.contains(&id.as_str())
}

/// Best-effort sysfs scan for an AMD GPU whose PCI device ID is on the
/// ROCm allowlist. Mirrors the PRIMARY classifier in the bash
/// `_amd_gpu_rocm_supported`: iterate `/sys/class/drm/card*/device`, keep
/// AMD vendor `0x1002` nodes, match the `device` ID against the allowlist.
/// Linux-only — on macOS (and any host without sysfs) `read_dir` fails and
/// this returns `false`, failing safe to the Vulkan EP. The bash helper's
/// SECONDARY `rocminfo` gfx probe stays installer-side (it only matters
/// when ROCm is already installed); the sysfs allowlist is authoritative
/// for the manifest.
fn detect_amd_rocm_capable() -> bool {
    let Ok(rd) = fs::read_dir("/sys/class/drm") else {
        return false;
    };
    for ent in rd.flatten() {
        let name = ent.file_name().to_string_lossy().to_string();
        if !name.starts_with("card") {
            continue;
        }
        let dev = ent.path().join("device");
        let Ok(vendor) = fs::read_to_string(dev.join("vendor")) else {
            continue;
        };
        if vendor.trim() != "0x1002" {
            continue; // AMD/ATI only
        }
        let Ok(device) = fs::read_to_string(dev.join("device")) else {
            continue;
        };
        if amd_rocm_supported(device.trim()) {
            return true;
        }
    }
    false
}

fn probe_runtimes() -> Runtimes {
    Runtimes {
        gstreamer: shell_out("gst-launch-1.0", &["--version"])
            .and_then(|s| s.lines().next().map(|l| l.to_string())),
        onnxruntime: detect_onnxruntime(),
        docker: shell_out("docker", &["--version"]),
    }
}

fn detect_onnxruntime() -> Option<String> {
    for p in [
        "/usr/local/lib/libonnxruntime.so",
        "/opt/onnxruntime/lib/libonnxruntime.so",
    ] {
        if std::path::Path::new(p).exists() {
            return Some(p.into());
        }
    }
    None
}

/// Map detected hardware to one of the capability-profile labels the edge
/// reports and the installer's `--force-profile` flag accepts (`intel-igpu`,
/// `intel-npu`, `hailo`, `amd-rocm`, `amd-vulkan`, `nvidia`, `cpu`, `dev`).
/// Mirrors the matrix in docs/HARDWARE_MATRIX.md — keep them in sync. The
/// label is advisory; the live config comes from `emit-config`.
fn recommend_profile(cpu: &CpuInfo, acc: &Accelerators) -> &'static str {
    let model = cpu.model_name.to_lowercase();
    if acc.nvidia_gpu {
        return "nvidia";
    }
    // EQR7 + Hailo-8 SKU. Detected by Hailo presence alone — regardless of
    // which AMD/Intel host CPU drives it. Engine still falls back to CPU EP
    // at runtime until M_HAILO_EP ships.
    if acc.hailo {
        return "hailo";
    }
    // Lunar Lake = Core Ultra 7 256V (Arc 140V iGPU + NPU 4).
    if acc.intel_arc_140v
        || acc.intel_npu
        || model.contains("core ultra 7 256v")
        || model.contains("core ultra 9 288v")
        || model.contains("lunar lake")
    {
        return "intel-npu";
    }
    // Discrete Arc (A310/A380/A580/A750/A770), Iris Xe, and UHD (N-series)
    // iGPUs all run the Intel GPU (OpenVINO) EP.
    if model.contains("arc a3") || model.contains("arc a5") || model.contains("arc a7") {
        return "intel-igpu";
    }
    if model.contains("i7-12700h") || model.contains("iris xe") || model.contains("96 eu") {
        return "intel-igpu";
    }
    if model.contains("n100")
        || model.contains("n150")
        || model.contains("n200")
        || model.contains("n305")
    {
        return "intel-igpu";
    }
    if acc.apple_silicon {
        return "dev";
    }
    // AMD-only (Radeon iGPU/dGPU, no Hailo): ROCm-capable discrete parts run
    // the ROCm EP; everything else routes to the Vulkan (WebGPU) EP.
    if acc.amd_rocm_capable {
        return "amd-rocm";
    }
    if acc.amd_igpu {
        return "amd-vulkan";
    }
    // Any remaining Intel iGPU not matched by model string.
    if acc.intel_igpu {
        return "intel-igpu";
    }
    // Fallback: no recognised accelerator — CPU EP.
    "cpu"
}

